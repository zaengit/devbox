use crate::LocalDomain;
use anyhow::{Context, Result, anyhow};
use std::collections::HashSet;
use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::Path;
use std::process::Stdio;
use tokio::io::AsyncReadExt;
use tokio::process::Command;
use tokio::time::{Duration, timeout};

pub fn validate_domains(domains: &[LocalDomain]) -> Result<()> {
    let mut names = HashSet::new();
    for route in domains {
        if !valid_local_domain(&route.domain) {
            return Err(anyhow!("{} is not a valid .localhost domain", route.domain));
        }
        if !names.insert(route.domain.to_ascii_lowercase()) {
            return Err(anyhow!(
                "domain {} is assigned more than once",
                route.domain
            ));
        }
        let upstream = route
            .upstream
            .strip_prefix("http://")
            .ok_or_else(|| anyhow!("upstream must use http:// with an unprivileged local port"))?;
        let (host, port) = upstream
            .rsplit_once(':')
            .ok_or_else(|| anyhow!("upstream must look like http://127.0.0.1:8080"))?;
        if !(host == "127.0.0.1" || host == "localhost" || host == "[::1]") {
            return Err(anyhow!("proxy upstream must point to loopback"));
        }
        let port: u16 = port
            .parse()
            .map_err(|_| anyhow!("upstream port must be a valid TCP port"))?;
        if port < 1024 {
            return Err(anyhow!("upstream ports below 1024 are not allowed"));
        }
    }
    Ok(())
}

pub fn render_caddyfile(domains: &[LocalDomain]) -> Result<String> {
    validate_domains(domains)?;
    let mut output = String::from(
        "# Generated by Devbox. HTTP only; configure HTTPS separately after reviewing certificate behavior.\n",
    );
    for route in domains {
        if route.websocket {
            output.push_str("# This route expects WebSocket traffic; Caddy reverse_proxy supports protocol upgrades.\n");
        }
        output.push_str(&format!(
            "http://{} {{\n    reverse_proxy {}\n}}\n\n",
            route.domain,
            route.upstream.trim_start_matches("http://")
        ));
    }
    Ok(output)
}

pub async fn validate_caddyfile(executable: &Path, config: &Path) -> Result<String> {
    let executable =
        crate::validate_executable(executable).context("validating Caddy executable")?;
    let config = config
        .canonicalize()
        .with_context(|| format!("resolving Caddyfile {}", config.display()))?;
    let mut child = Command::new(executable)
        .args(["validate", "--config"])
        .arg(config)
        .args(["--adapter", "caddyfile"])
        .stdin(Stdio::null())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .kill_on_drop(true)
        .spawn()
        .context("starting Caddy configuration validation")?;
    let stdout = child
        .stdout
        .take()
        .ok_or_else(|| anyhow!("could not capture Caddy validation output"))?;
    let stderr = child
        .stderr
        .take()
        .ok_or_else(|| anyhow!("could not capture Caddy validation diagnostics"))?;
    let stdout_task = tokio::spawn(read_limited(stdout));
    let stderr_task = tokio::spawn(read_limited(stderr));
    let status = timeout(Duration::from_secs(8), child.wait())
        .await
        .map_err(|_| anyhow!("Caddy validation timed out after 8 seconds"))??;
    let stdout = stdout_task.await??;
    let stderr = stderr_task.await??;
    let detail = [stdout, stderr]
        .into_iter()
        .filter(|part| !part.trim().is_empty())
        .collect::<Vec<_>>()
        .join("\n");
    if !status.success() {
        return Err(anyhow!(
            "Caddy rejected the configuration{}",
            if detail.is_empty() {
                String::new()
            } else {
                format!(": {detail}")
            }
        ));
    }
    Ok(if detail.is_empty() {
        "Caddy configuration is valid".into()
    } else {
        detail
    })
}

/// Write a user-approved Caddyfile location after validating a temporary file.
/// The previous file is preserved at `<name>.devbox-backup`.
pub async fn install_caddyfile(executable: &Path, target: &Path, config: String) -> Result<String> {
    let executable = executable.to_path_buf();
    let target = target.to_path_buf();
    let (target, temporary, backup) =
        tokio::task::spawn_blocking(move || prepare_caddyfile(&target, &config)).await??;
    let validation = validate_caddyfile(&executable, &temporary).await;
    if let Err(error) = validation {
        let _ = fs::remove_file(&temporary);
        return Err(error);
    }
    tokio::task::spawn_blocking(move || -> Result<String> {
        let had_previous = target.exists();
        if had_previous { fs::rename(&target, &backup).with_context(|| format!("preserving previous config at {}", backup.display()))?; }
        if let Err(error) = fs::rename(&temporary, &target) {
            if had_previous { let _ = fs::rename(&backup, &target); }
            let _ = fs::remove_file(&temporary);
            return Err(error).with_context(|| format!("installing Caddyfile at {}", target.display()));
        }
        Ok(if had_previous {
            format!("Validated and wrote {}. Previous config saved to {}. Reload Caddy from your own service manager after reviewing the change.", target.display(), backup.display())
        } else {
            format!("Validated and wrote {}. Reload Caddy from your own service manager after reviewing the change.", target.display())
        })
    }).await?
}

pub async fn restore_caddyfile(target: &Path) -> Result<String> {
    let target = target.to_path_buf();
    tokio::task::spawn_blocking(move || -> Result<String> {
        let file_name = target.file_name().ok_or_else(|| anyhow!("choose a Caddyfile path with a file name"))?;
        let parent = target.parent().filter(|parent| !parent.as_os_str().is_empty()).unwrap_or(Path::new("."));
        let parent = parent.canonicalize().with_context(|| format!("resolving config directory {}", parent.display()))?;
        #[cfg(target_os = "linux")]
        {
            use std::os::unix::fs::MetadataExt;
            if fs::metadata(&parent)?.uid() != unsafe { libc::geteuid() } { return Err(anyhow!("config directory must be owned by the current user")); }
        }
        let target = parent.join(file_name);
        let mut backup_name = file_name.to_os_string();
        backup_name.push(".devbox-backup");
        let backup = parent.join(backup_name);
        let backup_metadata = fs::symlink_metadata(&backup).with_context(|| format!("reading previous config backup {}", backup.display()))?;
        if !backup_metadata.file_type().is_file() { return Err(anyhow!("Caddyfile backup must be a regular file")); }
        #[cfg(target_os = "linux")]
        {
            use std::os::unix::fs::MetadataExt;
            if backup_metadata.uid() != unsafe { libc::geteuid() } { return Err(anyhow!("Caddyfile backup must be owned by the current user")); }
        }
        if target.exists() && !fs::symlink_metadata(&target)?.file_type().is_file() { return Err(anyhow!("Caddyfile target must be a regular file")); }
        let temporary = parent.join(format!(".devbox-restore-{}.tmp", uuid::Uuid::new_v4()));
        let mut file = OpenOptions::new().write(true).create_new(true).open(&temporary)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            file.set_permissions(fs::Permissions::from_mode(0o600))?;
        }
        std::io::copy(&mut fs::File::open(&backup)?, &mut file)?;
        file.sync_all()?;
        fs::rename(&temporary, &target).with_context(|| format!("restoring previous config at {}", target.display()))?;
        Ok(format!("Restored {} from {}. Reload Caddy from your own service manager after reviewing the change.", target.display(), backup.display()))
    }).await?
}

fn prepare_caddyfile(
    target: &Path,
    config: &str,
) -> Result<(std::path::PathBuf, std::path::PathBuf, std::path::PathBuf)> {
    if config.len() > 256 * 1024 {
        return Err(anyhow!("generated Caddyfile exceeds the 256 KiB limit"));
    }
    let file_name = target
        .file_name()
        .ok_or_else(|| anyhow!("choose a Caddyfile path with a file name"))?;
    let parent = target
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let parent = parent
        .canonicalize()
        .with_context(|| format!("resolving config directory {}", parent.display()))?;
    #[cfg(target_os = "linux")]
    {
        use std::os::unix::fs::MetadataExt;
        if std::fs::metadata(&parent)?.uid() != unsafe { libc::geteuid() } {
            return Err(anyhow!(
                "config directory must be owned by the current user"
            ));
        }
    }
    let target = parent.join(file_name);
    if target.exists() {
        let metadata = fs::symlink_metadata(&target)?;
        if !metadata.file_type().is_file() {
            return Err(anyhow!(
                "Caddyfile target must be a regular file, not a symlink or directory"
            ));
        }
        #[cfg(target_os = "linux")]
        {
            use std::os::unix::fs::MetadataExt;
            if metadata.uid() != unsafe { libc::geteuid() } {
                return Err(anyhow!(
                    "existing Caddyfile must be owned by the current user"
                ));
            }
        }
    }
    let mut backup_name = file_name.to_os_string();
    backup_name.push(".devbox-backup");
    let backup = parent.join(backup_name);
    if target.exists() && backup.exists() {
        return Err(anyhow!(
            "backup file {} already exists; move it before applying another config",
            backup.display()
        ));
    }
    let temporary = parent.join(format!(".devbox-{}.tmp", uuid::Uuid::new_v4()));
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temporary)
        .with_context(|| format!("creating temporary config in {}", parent.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        file.set_permissions(fs::Permissions::from_mode(0o600))?;
    }
    file.write_all(config.as_bytes())?;
    file.sync_all()?;
    Ok((target, temporary, backup))
}

fn valid_local_domain(domain: &str) -> bool {
    if domain.len() > 253 || !domain.to_ascii_lowercase().ends_with(".localhost") {
        return false;
    }
    let labels = domain.split('.').collect::<Vec<_>>();
    labels.len() >= 2
        && labels.iter().all(|label| {
            !label.is_empty()
                && label.len() <= 63
                && label.as_bytes()[0].is_ascii_alphanumeric()
                && label.as_bytes()[label.len() - 1].is_ascii_alphanumeric()
                && label
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
        })
}

async fn read_limited<R: tokio::io::AsyncRead + Unpin>(mut reader: R) -> Result<String> {
    let mut bytes = vec![0; 16 * 1024 + 1];
    let read = reader.read(&mut bytes).await?;
    bytes.truncate(read.min(16 * 1024));
    Ok(String::from_utf8_lossy(&bytes).trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn route(domain: &str, upstream: &str) -> LocalDomain {
        LocalDomain {
            id: "route".into(),
            project_id: "project".into(),
            domain: domain.into(),
            upstream: upstream.into(),
            websocket: true,
        }
    }

    #[test]
    fn renders_local_routes_and_rejects_conflicts_or_non_loopback_targets() {
        let config = render_caddyfile(&[route("api.localhost", "http://127.0.0.1:8080")]).unwrap();
        assert!(config.contains("http://api.localhost"));
        assert!(config.contains("reverse_proxy 127.0.0.1:8080"));
        assert!(
            validate_domains(&[
                route("api.localhost", "http://127.0.0.1:8080"),
                route("api.localhost", "http://localhost:8081")
            ])
            .is_err()
        );
        assert!(validate_domains(&[route("api.example.com", "http://127.0.0.1:8080")]).is_err());
        assert!(validate_domains(&[route("api.localhost", "http://0.0.0.0:8080")]).is_err());
    }
}
